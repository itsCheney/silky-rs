/// The pictures of a gallery entry, as indices into [`CG_IMAGES`].
pub fn entry_images(entry: usize) -> Vec<usize> {
    let Some(key) = CG_ENTRIES.get(entry).map(|e| &e[..5]) else {
        return Vec::new();
    };
    CG_IMAGES
        .iter()
        .enumerate()
        .filter(|(_, layers)| layers[0].starts_with(key))
        .map(|(i, _)| i)
        .collect()
}

